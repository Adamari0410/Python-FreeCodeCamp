#===================Como funciona las asignaciones aumentadas==========================

#tenemos +=,-=,*=, **=, //=, /=

mi_numero=20

mi_numero += 34
print(mi_numero)

mi_numero *= 3
print(mi_numero)

mi_numero -= 4
print(mi_numero)

mi_numero /= 9
print(mi_numero)

mi_numero %= 5
print(mi_numero)
mi_numero //=2.5
print(mi_numero)
mi_numero **=3
print(mi_numero)

